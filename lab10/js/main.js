console.log("\n--- Завдання 5: Реалізація функції checkType(value) ---");

// Функція checkType(value)
function checkType(value) {
    // Оператор typeof повертає рядок із типом даних.
    // Зокрема, typeof null повертає "object", що відповідає очікуваному результату у завданні. [cite: 58, 124]
    return typeof value;
}

console.log(`checkType(10): "${checkType(10)}"`);        // Очікується: "number" [cite: 122]
console.log(`checkType("Hello"): "${checkType("Hello")}"`);  // Очікується: "string" [cite: 123]
console.log(`checkType(null): "${checkType(null)}"`);    // Очікується: "object" [cite: 124]
console.log(`checkType(undefined): "${checkType(undefined)}"`); // Додаткова перевірка: "undefined" [cite: 59]
console.log(`checkType({}): "${checkType({})}"`);        // Додаткова перевірка: "object" [cite: 60]