console.log("\n--- Завдання 3: Приведення типів ---");

// Передбачення: "55". 
// Пояснення: Оператор '+' з рядком виконує конкатенацію. Число 5 приводиться до рядка "5". [cite: 64]
console.log(`5 + "5": ${5 + "5"}`);  

// Передбачення: 3. 
// Пояснення: Оператор '-' змушує рядок "5" привестись до числа 5, виконується віднімання. [cite: 65]
console.log(`"5" - 2: ${"5" - 2}`);  

// Передбачення: 1. 
// Пояснення: Булеві значення приводяться до чисел (true=1, false=0). 1 + 0 = 1.
console.log(`true + false: ${true + false}`);  

// Передбачення: 1. 
// Пояснення: null при арифметичних операціях приводиться до числа 0. 0 + 1 = 1.
console.log(`null + 1: ${null + 1}`);  

// Передбачення: NaN. 
// Пояснення: undefined при арифметичних операціях приводиться до NaN (Not a Number). NaN + 1 = NaN.
console.log(`undefined + 1: ${undefined + 1}`);  

// Передбачення: true. 
// Пояснення: Нестроге порівняння '==' виконує приведення типів. false приводиться до числа 0. 0 == 0. [cite: 66]
console.log(`0 == false: ${0 == false}`);  

// Передбачення: false. 
// Пояснення: Строге порівняння '===' не виконує приведення типів. Типи (number та boolean) різні. [cite: 67]
console.log(`0 === false: ${0 === false}`); 


